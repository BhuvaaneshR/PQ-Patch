"""
stub_client.py - a local, offline fake model.

Supplied with the capstone starter kit. This is the Lab 6 stub with one mode
added, stub:badargs. Every other mode behaves exactly as it did in Lab 6.
DO NOT EDIT THIS FILE.
The marking harness uses its own copy of this exact file. If you change
yours, your acceptance checks stop meaning anything.

WHAT IT IS
    A fake model that never touches the network, needs no API key, costs
    nothing, and returns the same thing every time. Its job is to let you
    trigger failures on purpose. You cannot ask a real model to return
    malformed JSON on demand; you can ask this one.

HOW TO USE IT
    In .env:
        LLM_BASE_URL=local://stub
        LLM_MODEL=stub:ok

    Change stub:ok to any mode below and run your program again.

THE FIFTEEN MODES
    stub:ok         your samples/valid_response.json, exactly as written
    stub:fenced     the same JSON wrapped in ```json ... ``` fences
    stub:preamble   the same JSON after a chatty sentence
    stub:malformed  the same JSON with a trailing comma (does not parse)
    stub:badshape   your samples/invalid_response.json, exactly as written
    stub:empty      an empty string
    stub:refused    a refusal message, in prose
    stub:error      raises StubError before returning anything

    New in Lab 5. These two exist so that retry behaviour can be tested:

    stub:flaky      raises StubError on the FIRST call of the process, then
                    returns your valid_response.json on every call after it.
                    A program that retries an error ends ok. One that does
                    not ends error.
    stub:ratelimit  raises StubRateLimitError on every call, carrying
                    status_code 429 and retry_after = 1 second. Nothing you
                    do makes it succeed. It exists to prove that your retry
                    loop has a cap and then gives up cleanly.

    The counter behind stub:flaky lives in this module, so it resets every
    time you start the program. One run of main.py sees one failure.

    New in Lab 6. These four exist so that injection and tool behaviour can
    be tested without depending on a real model's mood:

    stub:obedient   looks at the context you sent it. If it finds something
                    that reads like an INSTRUCTION, it obeys it: it returns
                    your valid_response.json with a marker appended to every
                    free-text field. If it finds none, it behaves like
                    stub:ok. It matches on PHRASINGS, and it generates the
                    marker itself, so deleting a string out of a document
                    does not stop it obeying. That is deliberate.
    stub:toolcall   calls topic_lookup, then question_lookup, then returns
                    your valid_response.json. Exercises the two round trips
                    and both tools.
    stub:traversal  calls topic_lookup three times: twice with a file path
                    where a topic name belongs, and once with the required
                    argument missing. Then it returns your
                    valid_response.json. Exercises containment (nothing
                    outside your data directory is ever opened) and argument
                    validation (a call that fails your Pydantic model is
                    refused before anything runs).
    stub:neverstop  returns a tool call every single time and never answers.
                    Exercises your loop cap. It has its own hard cap of
                    STUB_HARD_CAP calls so that a marking run cannot hang;
                    your program is expected to stop a long way below it.

    New for the capstone. One mode, for floor item 6 on the tools path:

    stub:badargs    reads the tools list your program sent with the request
                    and calls the FIRST tool in it with an empty argument
                    object, {}. Any tool with at least one required argument
                    must refuse that call before it runs, and log
                    tool_arg_rejected. It does this on the first call of the
                    process only; every later call returns your
                    valid_response.json, so a program that refuses the call
                    and carries on ends ok. It never loops. If the request
                    carries no tools, it behaves as stub:error.

    WHY stub:obedient EXISTS
        Injection against a real free-tier model is unreliable. The same
        payload lands on Tuesday and fails on Wednesday. Without a
        deterministic mode the red-team half of Lab 6 would be unmarkable,
        and worse, some of you would conclude your app is secure on the
        evidence of a lucky day. This is not a weaker model. It is a fixed
        instrument, so what you measure is your own defence and not the
        weather.

TWO FILES YOU MUST CREATE
    samples/valid_response.json
        One reply, in YOUR schema, that your program must accept.
    samples/invalid_response.json
        One reply that is valid JSON but that your validation must REJECT.

    The stub does not know or care what shape you chose. That is the point:
    everyone's schema is different, and the same stub tests all of them.
"""

import json
import os
import re
from pathlib import Path


class StubError(RuntimeError):
    """Raised by stub:error. Stands in for a network or provider failure."""


class StubRateLimitError(StubError):
    """Raised by stub:ratelimit. Stands in for an HTTP 429 from a provider.

    It is a StubError, so code that already catches StubError keeps working.
    Catch this one separately if you want to honour retry_after.
    """

    def __init__(self, message: str, retry_after: float = 1.0):
        super().__init__(message)
        self.status_code = 429
        self.retry_after = retry_after


_REFUSAL = (
    "I'm sorry, but I can't help with that. I'm not able to generate "
    "questions on this topic."
)

_PREAMBLE = "Sure! Here's the JSON you asked for:\n\n"

_CALL_LOG = ".stub_calls.log"

# --------------------------------------------------------------------------
# New in Lab 6
# --------------------------------------------------------------------------

# What stub:obedient appends when it obeys. It is generated HERE, not read
# out of any document, so removing a token from the corpus does not prevent
# the stub obeying.
CANARY = "PWNED-7F3A"

# stub:neverstop stops itself here so that a marking run cannot hang. Your
# own cap should be a long way below this.
STUB_HARD_CAP = 50

# What stub:obedient treats as an instruction. Phrasings, not tokens.
INJECTION_PATTERNS = [
    re.compile(r"ignore\s+(all\s+|any\s+)?(previous|prior|earlier|above)\s+instructions", re.I),
    re.compile(r"disregard\s+(the\s+|all\s+|any\s+)?(above|previous|prior|earlier)", re.I),
    re.compile(r"(system|assistant|admin)\s*(note|directive|override|message)\s*:", re.I),
    re.compile(r"you\s+must\s+(now\s+)?append", re.I),
    re.compile(r"new\s+instructions?\s+for\s+the\s+(assistant|model|ai)", re.I),
]


def _messages_text(messages) -> str:
    """Everything the caller sent, flattened into one string."""
    parts = []
    for m in (messages or []):
        if not isinstance(m, dict):
            continue
        content = m.get("content")
        if isinstance(content, str):
            parts.append(content)
        elif isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and isinstance(block.get("text"), str):
                    parts.append(block["text"])
    return "\n".join(parts)


def _looks_like_instruction(text: str) -> bool:
    return any(p.search(text) for p in INJECTION_PATTERNS)


def _taint(value):
    """Obey: append the canary to every free-text field.

    Short strings are left alone so that enum-like and identifier fields in
    your schema still validate. The attack is meant to succeed against an
    undefended program, not to be caught by accident.
    """
    if isinstance(value, str):
        return f"{value} {CANARY}" if len(value) > 10 else value
    if isinstance(value, list):
        return [_taint(v) for v in value]
    if isinstance(value, dict):
        return {k: _taint(v) for k, v in value.items()}
    return value


class _ToolCallReply:
    """Marker returned by _content_for when the model wants to call a tool."""

    def __init__(self, call_id: str, name: str, arguments: dict):
        self.call_id = call_id
        self.name = name
        self.arguments = arguments

# How many times each mode has been called in THIS process. Reset on every
# run of your program, which is what makes stub:flaky fail exactly once.
_CALLS: dict[str, int] = {}


def _nth_call(mode: str) -> int:
    _CALLS[mode] = _CALLS.get(mode, 0) + 1
    return _CALLS[mode]


# --------------------------------------------------------------------------
# Loading your samples
# --------------------------------------------------------------------------

def _samples_dir() -> Path:
    return Path(os.getenv("STUB_SAMPLES_DIR", "samples"))


def _load_sample(name: str) -> str:
    path = _samples_dir() / name
    if not path.exists():
        raise StubError(
            f"{path} not found.\n"
            f"The stub returns YOUR sample replies, so you have to write them.\n"
            f"Create {path} containing one reply in your own schema.\n"
            f"See the comment at the top of stub_client.py."
        )
    text = path.read_text(encoding="utf-8").strip()
    try:
        json.loads(text)
    except json.JSONDecodeError as exc:
        raise StubError(
            f"{path} is not valid JSON ({exc}).\n"
            f"Both sample files must be valid JSON. "
            f"invalid_response.json is meant to be valid JSON that your "
            f"VALIDATION rejects, not text that json.loads rejects."
        ) from exc
    return text


def _break_json(text: str) -> str:
    """Insert a trailing comma before the last closing bracket."""
    i = max(text.rfind("}"), text.rfind("]"))
    if i == -1:
        return text + ","
    return text[:i] + "," + text[i:]


def _content_for(mode: str, messages=None, tools=None):
    if mode == "ok":
        return _load_sample("valid_response.json")
    if mode == "fenced":
        return "```json\n" + _load_sample("valid_response.json") + "\n```"
    if mode == "preamble":
        return _PREAMBLE + _load_sample("valid_response.json")
    if mode == "malformed":
        return _break_json(_load_sample("valid_response.json"))
    if mode == "badshape":
        return _load_sample("invalid_response.json")
    if mode == "empty":
        return ""
    if mode == "refused":
        return _REFUSAL
    if mode == "error":
        raise StubError("stub:error - simulated provider failure")
    if mode == "flaky":
        if _nth_call("flaky") == 1:
            raise StubError(
                "stub:flaky - simulated transient failure on the first call"
            )
        return _load_sample("valid_response.json")
    if mode == "ratelimit":
        _nth_call("ratelimit")
        raise StubRateLimitError(
            "stub:ratelimit - 429 Too Many Requests (simulated)",
            retry_after=1.0,
        )

    # ---------------------------------------------------------- Lab 6 modes
    if mode == "obedient":
        text = _load_sample("valid_response.json")
        if _looks_like_instruction(_messages_text(messages)):
            return json.dumps(_taint(json.loads(text)))
        return text

    if mode == "toolcall":
        n = _nth_call("toolcall")
        if n == 1:
            return _ToolCallReply(
                "call_topic_1", "topic_lookup",
                {"query": "assessment", "source": "topics.json"})
        if n == 2:
            return _ToolCallReply(
                "call_question_1", "question_lookup", {"query": "assessment"})
        return _load_sample("valid_response.json")

    if mode == "traversal":
        n = _nth_call("traversal")
        if n == 1:
            # A path where a topic name belongs. A topic name is not a file
            # name; a tool that opens what it is handed reads this one.
            return _ToolCallReply(
                "call_traversal_1", "topic_lookup", {"query": "../.env"})
        if n == 2:
            # The same again, but pointing at something that parses, so a tool
            # that opens it succeeds instead of failing on the JSON.
            return _ToolCallReply(
                "call_traversal_2", "topic_lookup",
                {"query": "../topics_backup.json"})
        if n == 3:
            # Gate 2: a call with the required argument missing. It fails the
            # Pydantic model whatever constraints you chose.
            return _ToolCallReply(
                "call_traversal_3", "topic_lookup", {"limit": 10})
        return _load_sample("valid_response.json")

    if mode == "neverstop":
        n = _nth_call("neverstop")
        if n >= STUB_HARD_CAP:
            raise StubError(
                f"stub:neverstop - reached its own hard cap of {STUB_HARD_CAP} "
                f"calls. Your program should have stopped a long way before this."
            )
        return _ToolCallReply(
            f"call_forever_{n}", "topic_lookup",
            {"query": f"assessment {n}", "source": "topics.json"})

    # ----------------------------------------------------- capstone mode
    if mode == "badargs":
        name = _first_tool_name(tools)
        if name is None:
            raise StubError(
                "stub:badargs - the request carried no tools, so there is no "
                "tool to call with bad arguments (behaves as stub:error)"
            )
        if _nth_call("badargs") == 1:
            # Required arguments missing altogether. This fails any argument
            # model with at least one required field, whatever constraints
            # you chose.
            return _ToolCallReply("call_badargs_1", name, {})
        return _load_sample("valid_response.json")

    raise StubError(
        f"Unknown stub mode: {mode!r}. "
        f"LLM_MODEL must be one of: stub:ok, stub:fenced, stub:preamble, "
        f"stub:malformed, stub:badshape, stub:empty, stub:refused, "
        f"stub:error, stub:flaky, stub:ratelimit, stub:obedient, "
        f"stub:toolcall, stub:traversal, stub:neverstop, stub:badargs"
    )


def _first_tool_name(tools):
    """The function name of the first tool in an OpenAI-style tools list.

    Returns None when there is no usable tools list, so that stub:badargs can
    behave as stub:error.
    """
    if not isinstance(tools, (list, tuple)) or not tools:
        return None
    first = tools[0]
    function = first.get("function") if isinstance(first, dict) else getattr(first, "function", None)
    if isinstance(function, dict):
        name = function.get("name")
    else:
        name = getattr(function, "name", None)
    if name is None and isinstance(first, dict):
        name = first.get("name")
    return name if isinstance(name, str) and name else None


# --------------------------------------------------------------------------
# A response object shaped like the one the OpenAI SDK returns
# --------------------------------------------------------------------------

class _Function:
    """The function half of a tool call, as the OpenAI SDK shapes it."""

    def __init__(self, name: str, arguments: dict):
        self.name = name
        self.arguments = json.dumps(arguments)


class _ToolCall:
    def __init__(self, call_id: str, name: str, arguments: dict):
        self.id = call_id
        self.type = "function"
        self.function = _Function(name, arguments)


class _Message:
    def __init__(self, content, tool_calls=None):
        self.role = "assistant"
        self.content = content
        self.tool_calls = tool_calls


class _Choice:
    def __init__(self, content):
        self.index = 0
        if isinstance(content, _ToolCallReply):
            self.message = _Message(
                None, [_ToolCall(content.call_id, content.name, content.arguments)])
            self.finish_reason = "tool_calls"
        else:
            self.message = _Message(content)
            self.finish_reason = "stop"


class _Usage:
    def __init__(self, prompt_tokens: int, completion_tokens: int):
        self.prompt_tokens = prompt_tokens
        self.completion_tokens = completion_tokens
        self.total_tokens = prompt_tokens + completion_tokens


class _Completion:
    def __init__(self, content, model: str, prompt_chars: int):
        self.id = "stub-completion"
        self.model = model
        self.choices = [_Choice(content)]
        out_chars = 0 if isinstance(content, _ToolCallReply) else len(content)
        self.usage = _Usage(max(1, prompt_chars // 4), max(1, out_chars // 4))


# --------------------------------------------------------------------------
# The client
# --------------------------------------------------------------------------

class _Completions:
    def __init__(self, model: str):
        self._model = model

    def create(self, model=None, messages=None, **kwargs):
        """Mimics client.chat.completions.create(...).

        Extra keyword arguments such as response_format or temperature are
        accepted and ignored, the way a low-tier free model often does. The
        one exception is tools, which only stub:badargs reads.
        """
        requested = model or self._model or "stub:ok"
        if not str(requested).startswith("stub:"):
            raise StubError(
                f"LLM_BASE_URL is local://stub but LLM_MODEL is {requested!r}. "
                f"When using the stub, LLM_MODEL must start with 'stub:'."
            )
        mode = str(requested).split(":", 1)[1].strip()

        prompt_chars = sum(
            len(str(m.get("content", ""))) for m in (messages or [])
        )
        try:
            with open(_CALL_LOG, "a", encoding="utf-8") as fh:
                fh.write(f"{requested}\t{prompt_chars}\n")
        except OSError:
            pass

        content = _content_for(mode, messages, kwargs.get("tools"))
        return _Completion(content, requested, prompt_chars)


class _Chat:
    def __init__(self, model: str):
        self.completions = _Completions(model)


class StubClient:
    """Drop-in stand-in for the OpenAI client, for the calls this course makes."""

    def __init__(self, model: str = "stub:ok"):
        self.model = model
        self.chat = _Chat(model)
